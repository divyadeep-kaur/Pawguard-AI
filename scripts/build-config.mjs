#!/usr/bin/env node
// Generates public/config.js from environment variables at build time (Vercel runs this via vercel.json).
//
//   SUPABASE_URL        e.g. https://abcdxyzcompany.supabase.co
//   SUPABASE_ANON_KEY   the *anon / publishable* key (Project Settings -> API)
//
// The anon key is designed to be public: Row Level Security is what protects the data.
// This script REFUSES to build a config containing a service_role / secret key.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const OUT = process.env.CONFIG_OUT || join(here, '..', 'public', 'config.js');
const env = process.env;

const url = (env.SUPABASE_URL || env.NEXT_PUBLIC_SUPABASE_URL || env.VITE_SUPABASE_URL || '').trim().replace(/\/+$/, '');
const key = (env.SUPABASE_ANON_KEY || env.SUPABASE_PUBLISHABLE_KEY || env.NEXT_PUBLIC_SUPABASE_ANON_KEY || env.VITE_SUPABASE_ANON_KEY || '').trim();

function fail(msg) {
  console.error(`\n[build-config] ERROR: ${msg}\n`);
  process.exit(1);
}

function jwtRole(token) {
  const parts = token.split('.');
  if (parts.length !== 3) return null;
  try {
    const payload = JSON.parse(Buffer.from(parts[1].replace(/-/g, '+').replace(/_/g, '/'), 'base64').toString('utf8'));
    return payload.role || null;
  } catch { return null; }
}

export function validate(url, key) {
  const problems = [];
  if (url) {
    let u;
    try { u = new URL(url); } catch { problems.push('SUPABASE_URL is not a valid URL.'); }
    if (u && u.protocol !== 'https:' && !/^(localhost|127\.0\.0\.1)$/.test(u.hostname)) problems.push('SUPABASE_URL must start with https://');
    if (u && u.pathname !== '/' && u.pathname !== '') problems.push('SUPABASE_URL must be the bare project URL (no path such as /rest/v1).');
  }
  if (key) {
    if (/^sb_secret_/.test(key)) problems.push('SUPABASE_ANON_KEY is a SECRET key (sb_secret_...). Use the publishable/anon key. Secret keys must never reach the browser.');
    else if (key.split('.').length === 3) {
      const r = jwtRole(key);
      if (r === 'service_role') problems.push('SUPABASE_ANON_KEY is the service_role key. That key bypasses Row Level Security and must NEVER be shipped to the browser. Use the anon key.');
      else if (r && r !== 'anon') problems.push(`SUPABASE_ANON_KEY has role "${r}", expected "anon".`);
      else if (!r) problems.push('SUPABASE_ANON_KEY looks like a JWT but could not be decoded.');
    } else if (!/^sb_publishable_/.test(key)) problems.push('SUPABASE_ANON_KEY is not a recognised anon (JWT) or publishable (sb_publishable_...) key.');
  }
  return problems;
}

// Only run the build when executed directly (not when imported by tests).
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  if (!!url !== !!key) fail(`Set BOTH SUPABASE_URL and SUPABASE_ANON_KEY (currently only ${url ? 'the URL' : 'the key'} is set).`);
  const problems = validate(url, key);
  if (problems.length) fail(problems.join('\n  '));

  const body = `// GENERATED by scripts/build-config.mjs at build time. Do not edit by hand.
// Contains only the public Supabase URL and anon key. Row Level Security protects the data.
// NEVER put the service_role key here.
window.PAWGUARD_CONFIG = ${JSON.stringify({ SUPABASE_URL: url, SUPABASE_ANON_KEY: key }, null, 2)};
`;
  writeFileSync(OUT, body);
  if (url) console.log(`[build-config] Supabase configured for ${new URL(url).host}; wrote ${OUT}`);
  else console.warn('[build-config] WARNING: SUPABASE_URL / SUPABASE_ANON_KEY not set. The site will deploy, but /portal will show "Accounts backend not connected" until you add them in Vercel -> Settings -> Environment Variables and redeploy.');
}
